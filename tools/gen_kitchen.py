#!/usr/bin/env python3
"""Render the Build screen's sprites in Blender.

    python3 tools/gen_kitchen.py [--samples 128] [--only key,key,...]

Reads the layouts from src/kitchens.js (through node, so there is one copy of them),
renders every distinct (object, turn) the kitchens use plus one empty room shell per
kitchen, and writes:

    assets/kitchen/<key>.png       an object, cropped, 256 colours
    assets/kitchen/room_<id>.png   a kitchen's floor and walls
    src/kitchen_sprites.js         GENERATED: the camera basis, scale and anchors

Needs Blender (see tools/sprite_common.py), node, numpy and Pillow. The objects are
modelled in code by tools/blender/kitchen_models.py — no source art is read.

Why offline and why Blender: the Build screen used to be live 3D on a painter's-
algorithm rasteriser, and it never looked right (§6 "The Build screen is 2D"). A
real renderer with a depth buffer, soft shadows and real materials gives far better
art than anything drawable at runtime, and the runtime only blits.
"""
import json
import os
import re
import subprocess

from sprite_common import (ROOT, HERE, run_blender, winpath, temp_dir, cleanup,
                           crop_quantise, arg)

OUT_DIR = os.path.join(ROOT, 'assets', 'kitchen')
OUT_JS = os.path.join(ROOT, 'src', 'kitchen_sprites.js')

# The one camera. Azimuth is measured from straight-on toward the right; the camera
# looks into the back-left corner, where every layout puts its wall-mounted objects.
AZIMUTH = 36
ELEVATION = 30
K = 190          # rendered pixels per world unit

def load_layouts():
    js = ("import('" + os.path.join(ROOT, 'src', 'kitchens.js') + "').then((m) => {"
          "const seen = new Map();"
          "for (const k of m.KITCHENS) for (const it of k.items) {"
          "  seen.set(m.spriteKey(it), { key: m.spriteKey(it), obj: it.obj, ry: it.ry || 0,"
          "    w: it.w, d: it.d, tone: it.tone, wall: m.WALL_MOUNTED.has(it.obj) }); }"
          "console.log(JSON.stringify({ sprites: [...seen.values()],"
          "  rooms: m.KITCHENS.map((k) => ({ id: k.id, room: k.room, tint: k.tint })) }));"
          "});")
    return json.loads(subprocess.check_output(['node', '-e', js], text=True))


def read_existing():
    if not os.path.exists(OUT_JS):
        return None
    m = re.search(r'/\*DATA\*/(.*)/\*END\*/', open(OUT_JS).read(), re.S)
    return json.loads(m.group(1)) if m else None


def main():
    samples = arg('--samples', '128')
    only = arg('--only', '')
    data = load_layouts()
    spec = dict(data, K=K, azimuth=AZIMUTH, elevation=ELEVATION)

    tmp = temp_dir()
    try:
        spec_path = os.path.join(tmp, 'spec.json')
        json.dump(spec, open(spec_path, 'w'))
        print(f'rendering {len(spec["sprites"])} sprites + {len(spec["rooms"])} rooms '
              f'at {samples} samples...')
        run_blender(os.path.join(HERE, 'blender', 'kitchen.py'),
                    [winpath(spec_path), winpath(tmp), samples, only],
                    'KITCHEN_DONE')
        meta = json.load(open(os.path.join(tmp, 'meta.json')))

        prev = read_existing() if only else None
        out = prev or {'K': K, 'R': meta.get('R'), 'U': meta.get('U'),
                       'sprites': {}, 'rooms': {}}
        if meta.get('R'):
            out['R'], out['U'] = meta['R'], meta['U']
        os.makedirs(OUT_DIR, exist_ok=True)
        total = 0
        for group, prefix in (('sprites', ''), ('rooms', 'room_')):
            for key, a in meta[group].items():
                name = prefix + key
                dst = os.path.join(OUT_DIR, name + '.png')
                x0, y0, w, h = crop_quantise(os.path.join(tmp, name + '.png'), dst)
                out[group][key] = {'w': w, 'h': h,
                                   'ax': round(a['ax'] - x0, 2), 'ay': round(a['ay'] - y0, 2)}
                size = os.path.getsize(dst)
                total += size
                print(f'  {name:14s} {w:4d}x{h:<4d} {size // 1024:4d} KB')
        print(f'  total {total // 1024} KB')
    finally:
        cleanup(tmp)

    # Drop sprites no layout uses any more, and their files, so a turn that changed
    # cannot leave a dead image in the manifest (and in the download).
    live = {sp['key'] for sp in spec['sprites']}
    for key in list(out['sprites']):
        if key not in live:
            del out['sprites'][key]
            stale = os.path.join(OUT_DIR, key + '.png')
            if os.path.exists(stale):
                os.remove(stale)
                print('  removed stale', key)

    js = ('// GENERATED by tools/gen_kitchen.py — do not edit. Re-run the tool instead.\n'
          '//\n'
          '// K: rendered pixels per world unit. R / U: the camera\'s right and up vectors\n'
          '// in Blender space (x, -z, y of the game\'s coordinates). ax/ay: where the\n'
          '// object\'s world origin sits inside its cropped image.\n'
          'export const KITCHEN_ART = /*DATA*/' + json.dumps(out) + '/*END*/;\n')
    open(OUT_JS, 'w').write(js)
    print('wrote', os.path.relpath(OUT_JS, ROOT))


if __name__ == '__main__':
    main()
