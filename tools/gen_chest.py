#!/usr/bin/env python3
"""Render the treasure chest's sprite frames in Blender.

    python3 tools/gen_chest.py [--samples 128]

Writes assets/chest/*.png (lid frames, three latches, the padlock) and
src/chest_sprites.js (GENERATED: each image's place in the shared frame, plus the
pivots the ceremony animates about).

Source: "Low Poly Chest [2.0]" by The_3Darknight, CC0, in assets/src (not shipped).
Needs Blender (see tools/sprite_common.py) and Pillow.

The chest used to be baked into triangles for the in-game 3D renderer, which could
only give each face one flat colour and had no depth buffer. Rendering it offline
keeps the model's painted texture, real shadows and the gold inside.
"""
import json
import os

from sprite_common import ROOT, HERE, run_blender, winpath, temp_dir, cleanup, crop_quantise, arg

GLB = os.path.join(ROOT, 'assets', 'src', 'Low_Poly_Chest [2.0]', 'Low_Poly_Chest [2.0] GLTF.glb')
OUT_DIR = os.path.join(ROOT, 'assets', 'chest')
OUT_JS = os.path.join(ROOT, 'src', 'chest_sprites.js')


def main():
    samples = arg('--samples', '128')
    tmp = temp_dir()
    try:
        print(f'rendering chest at {samples} samples...')
        run_blender(os.path.join(HERE, 'blender', 'chest.py'),
                    [winpath(GLB), winpath(tmp), samples], 'CHEST_DONE')
        meta = json.load(open(os.path.join(tmp, 'meta.json')))
        os.makedirs(OUT_DIR, exist_ok=True)
        names = [f'lid_{i}' for i in range(len(meta['lidAngles']))] + \
                ['latch_0', 'latch_1', 'latch_2', 'lock']
        rects = {}
        total = 0
        for n in names:
            dst = os.path.join(OUT_DIR, n + '.png')
            x, y, w, h = crop_quantise(os.path.join(tmp, n + '.png'), dst)
            rects[n] = [x, y, w, h]
            total += os.path.getsize(dst)
            print(f'  {n:8s} {w:4d}x{h:<4d} {os.path.getsize(dst) // 1024:4d} KB')
        print(f'  total {total // 1024} KB')
    finally:
        cleanup(tmp)
    meta['rects'] = rects
    js = ('// GENERATED by tools/gen_chest.py — do not edit. Re-run the tool instead.\n'
          '//\n'
          '// Every image is a crop of one shared square frame of side `res` pixels:\n'
          '// rects[name] = [x, y, w, h] within it. Points are pixels in that frame.\n'
          'export const CHEST_ART = ' + json.dumps(meta) + ';\n')
    open(OUT_JS, 'w').write(js)
    print('wrote', os.path.relpath(OUT_JS, ROOT))


if __name__ == '__main__':
    main()
